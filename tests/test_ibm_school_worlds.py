                with mock.patch.object(safety, "load_recovery_snapshot", side_effect=load_then_race):
                    result = self.execute(generator=generator)
                self.assert_blocked(result, "SNAPSHOT_INVALID", before_scope=True)
                self.assertIs(result["restore_created"], True)
                self.assertEqual(self.restore_scope, result["restore_scope"])
                self.assertEqual("REQUEST", result["stage"])
                generator.assert_not_called()
                self.assertEqual([], self.fx.calls)

