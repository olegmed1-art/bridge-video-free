    def test_journal_replace_or_append_after_loading_blocks_before_generation(self):
        for number, fault in enumerate(("replace", "append")):
            with self.subTest(fault=fault):
                if number:
                    self.make_fixture()
                load = safety.load_recovery_snapshot

                def load_then_race(op, payload, prefix="rollback"):
                    load(op, payload, prefix=prefix)
                    last_name = sorted(self.journal_before)[-1]
                    if fault == "replace":
                        self.corrupt_archive_file(self.archive / last_name)
