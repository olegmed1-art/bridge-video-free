    def test_guards_block_before_generator_on_drift_journal_gate_hash_allow_and_busy_cgroup(self):
        faults = ("config_bytes", "gate_bytes", "missing_gate", "gate_condition", "gate_not_loaded",
                  "unknown_terminal", "missing_journal", "snapshot_hash", "allow_path",
                  "unit_active", "unit_job", "unit_pid", "cgroup_busy")
        for number, fault in enumerate(faults):
            with self.subTest(fault=fault):
                if number:
                    self.make_fixture()
                expected = None
                if fault == "config_bytes":
                    path = self.fx.root / self.fx.rows[safety.CONTROL]["FragmentPath"].lstrip("/")
                    path.write_bytes(path.read_bytes() + b"# drift\n")
                    expected = "FILE_DRIFT"
                elif fault == "gate_bytes":
                    Path(next(iter(self.gates_before))).write_bytes(b"[Unit]\n# drift\n")
                    expected = "FILE_DRIFT"
                elif fault == "missing_gate":
                    Path(next(iter(self.gates_before))).unlink()
                    expected = "FILE_DRIFT"
                elif fault == "gate_condition":
                    self.fx.conditions[safety.OBSERVER] = []
                    expected = "GATE_NOT_EFFECTIVE"
                elif fault == "gate_not_loaded":
                    self.fx.rows[safety.OBSERVER]["NeedDaemonReload"] = "yes"
                    expected = "GATE_NOT_EFFECTIVE"
                elif fault == "unknown_terminal":
                    last_name = sorted(self.journal_before)[-1]
                    last = json.loads(self.journal_before[last_name])
                    event = dict(seq=last["seq"] + 1,
                                 previous_sha256=hashlib.sha256(self.journal_before[last_name]).hexdigest(),
                                 event="UNKNOWN_TERMINAL")
                    (self.archive / f'journal-{event["seq"]:03d}.json').write_bytes(safety.canonical(event))
                    expected = "SNAPSHOT_INVALID"
                elif fault == "missing_journal":
                    (self.archive / "journal-004.json").unlink()
                    expected = "SAFETY_GUARD_BLOCKED"
                elif fault == "snapshot_hash":
                    self.corrupt_archive_file(self.archive / "snapshot.json")
                    expected = "SAFETY_GUARD_BLOCKED"
                elif fault == "allow_path":
                    self.allow.write_bytes(b"unexpected\n")
                    expected = "COLLISION"
                elif fault == "unit_active":
                    self.fx.rows[safety.BEN].update(ActiveState="active", SubState="running")
                    expected = "UNIT_BUSY"
                elif fault == "unit_job":
                    self.fx.rows[safety.HEALTH]["Job"] = "93"
                    expected = "UNIT_BUSY"
                elif fault == "unit_pid":
                    self.fx.rows[safety.BRIDGE]["MainPID"] = "77"
                    expected = "UNIT_BUSY"
                else:
                    group = "/system.slice/" + safety.CONTROL
                    directory = self.fx.root / ("sys/fs/cgroup" + group)
                    directory.mkdir(exist_ok=True)
                    (directory / "cgroup.events").write_text("populated 1\nfrozen 0\n")
                    (directory / "cgroup.procs").write_text("77\n")
                    self.fx.rows[safety.CONTROL]["ControlGroup"] = group
                    expected = "CGROUP_NOT_EMPTY"
                generator = mock.Mock(side_effect=AssertionError("GENERATOR_MUST_NOT_RUN"))
                result = self.execute(generator=generator)
                self.assert_blocked(result, expected, before_scope=True)
                generator.assert_not_called()

