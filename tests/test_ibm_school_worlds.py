def request(snapshot_sha256):
    return dict(schema=worlds.REQUEST_SCHEMA, operation="generate_worlds",
                run_id="38129999999", attempt=1, head="b" * 40,
                identity=dict(safety.IDENTITY), transport=dict(safety.TRANSPORT),
                snapshot_id=worlds.SNAPSHOT_ID, snapshot_sha256=snapshot_sha256)


class FixedSchoolWorldsTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.good = generate_worlds(**json.loads(validator.INPUT_BYTES))
        cls.good_bytes = worlds.canonical(cls.good)
        # Never patch the workload, generator, or reference-result digest.
        cls.good_sha256 = hashlib.sha256(cls.good_bytes).hexdigest()
        if cls.good_sha256 != validator.EXPECTED_RESULT_SHA256:
            raise AssertionError("Real generator does not match the approved result")

    def setUp(self):
        network = mock.patch("socket.socket.connect",
                             side_effect=AssertionError("LIVE_NETWORK_FORBIDDEN"))
        network.start()
        self.addCleanup(network.stop)
        self.make_fixture()

    def make_fixture(self):
        """Build the historical partial archive, then its exact continuation."""
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        harness = fixtures.SnapshotResumeTests(methodName="runTest")
        self.addCleanup(harness.doCleanups)
        harness.partial(temporary.name)
        harness.p.update(run_id=worlds.ISOLATED_RUN, head=worlds.ISOLATED_HEAD)
        resumed = harness.execute()
        self.assertEqual(("ISOLATED_TARGET_SCOPE", "OK"),
                         (resumed["result"], resumed["reason"]), resumed)
        self.assertEqual(worlds.SNAPSHOT_ID, resumed["snapshot_id"])
        self.fx = harness.fx
        self.archive = harness.archive
        self.fixture_sha = harness.fixture_sha
        self.p = request(self.fixture_sha)
        self.scope = (safety.RECOVERY_ROOT + "/worlds-" + self.p["run_id"]
                      + "-" + self.p["head"][:12])
        self.scope_path = self.fx.root / self.scope.lstrip("/")
        self.restore_scope = (safety.RECOVERY_ROOT + "/" + worlds.SNAPSHOT_ID
                              + "/resume-restore-" + self.p["run_id"] + "-" + self.p["head"][:12])
        self.restore_path = self.fx.root / self.restore_scope.lstrip("/")
        self.snapshot_before = (self.archive / "snapshot.json").read_bytes()
        self.journal_before = {
            path.name: path.read_bytes()
            for path in sorted(self.archive.glob("journal-*.json"))
        }
        events = [json.loads(raw) for raw in self.journal_before.values()]
        self.assertEqual("ISOLATED_TARGET_SCOPE", events[-1]["event"])
        bound = [event for event in events if event["event"] == "CONTINUATION_BOUND"]
        self.assertEqual(1, len(bound))
        self.assertEqual((worlds.ISOLATED_RUN, worlds.ISOLATED_HEAD),
                         (bound[0]["run_id"], bound[0]["head"]))
        fs = safety.RootFS(self.fx.root)
        self.gates_before = {
            str(path): (path.read_bytes(), fs.record("/" + str(path.relative_to(self.fx.root))))
            for path in harness.gates()
        }
        self.assertEqual(5, len(self.gates_before))
        self.assertEqual(set(safety.GATE_UNITS),
                         {Path(path).parent.name[:-2] for path in self.gates_before})
        self.allow = (self.fx.root / "etc/systemd/system"
                      / (".bridge-ibm-isolation-" + worlds.SNAPSHOT_ID + ".allow"))
        self.fx.calls.clear()
        self.fx.diag_calls.clear()
        self.fx.stop_requested.clear()
        self.fx.reloads = 0

    def execute(self, *, generator=None, started=None, payload=None, **overrides):
        kwargs = self.fx.kwargs()
        kwargs.pop("sleep")  # The worlds entrypoint deliberately has no sleep hook.
        if generator is not None:
            kwargs["generator"] = generator
        if started is not None:
            kwargs["started"] = started
        kwargs.update(overrides)
        # Fixture inode/timestamp metadata changes its archive digest only.
        with mock.patch.object(worlds, "SNAPSHOT_SHA256", self.fixture_sha):
            result = worlds.execute(self.p if payload is None else payload, **kwargs)
        self.assertNotIn(self.fx.secret, json.dumps(result))
        self.assertLessEqual(len(worlds.canonical(result)), worlds.MAX_RECEIPT)
        self.assertEqual([], result["changes"])
        self.assert_read_only_calls()
        return result

    def repeated_good(self, **_kwargs):
        return copy.deepcopy(self.good)

    @staticmethod
    def corrupt_archive_file(path):
        # Immutable production files are mode 0400. This fault is confined to
        # the owned temporary fixture and must work as an unprivileged tester.
        path.chmod(0o600)
        path.write_bytes(path.read_bytes() + b" ")
        path.chmod(0o400)

    def assert_read_only_calls(self):
        self.assertEqual([], self.fx.stop_requested)
        self.assertEqual(0, self.fx.reloads)
        for argv in self.fx.calls:
            self.assertTrue(
                argv[:2] == ["/usr/bin/systemctl", "show"] or
                argv[:4] == ["/usr/bin/busctl", "--system", "--json=short", "get-property"],
                argv,
            )
            for forbidden in ("start", "stop", "restart", "reload", "daemon-reload",
                              "disable", "mask", "StartUnit", "StopUnit", "RestartUnit",
                              "ReloadUnit", "CancelJob", "KillUnit", "docker", "psql"):
                self.assertNotIn(forbidden, argv)

    def assert_immutable_evidence(self):
        self.assertEqual(self.snapshot_before, (self.archive / "snapshot.json").read_bytes())
        self.assertEqual(self.journal_before, {
            path.name: path.read_bytes() for path in sorted(self.archive.glob("journal-*.json"))
        })
        fs = safety.RootFS(self.fx.root)
        for path, (raw, record) in self.gates_before.items():
            path = Path(path)
            self.assertEqual(raw, path.read_bytes())
            self.assertEqual(record, fs.record("/" + str(path.relative_to(self.fx.root))))
        self.assertFalse(self.allow.exists())

    def assert_blocked(self, result, reason=None, *, before_scope=False):
        self.assertEqual("BLOCKED", result["result"], result)
        if reason is not None:
            self.assertEqual(reason, result["reason"], result)
        self.assertIsNone(result["artifact"])
        if before_scope:
            self.assertIsNone(result["output_scope"])
            self.assertFalse(result["scope_created"])
            self.assertFalse(self.scope_path.exists())

    def test_real_generator_produces_256_verified_worlds_and_identical_repeat(self):
        trace = []
        writes = []
        directories = []
        restores = []
        verify_quiet = worlds.verify_quiet
        write = safety.RootFS.write_new
        mkdir = safety.RootFS.mkdir
        restore = safety.RootFS.restore_record

        def tracked_write(fs, path, data, **kwargs):
            writes.append(path)
            return write(fs, path, data, **kwargs)

        def tracked_mkdir(fs, path, **kwargs):
            directories.append(path)
            return mkdir(fs, path, **kwargs)

        def tracked_restore(fs, record, path):
            restores.append(path)
            return restore(fs, record, path)

        def verified(op):
            verify_quiet(op)
            trace.append("quiet-and-all-five-gates")

        def real_generator(**kwargs):
            self.assertEqual(json.loads(validator.INPUT_BYTES), kwargs)
            self.assertIn("quiet-and-all-five-gates", trace)
            self.assertFalse(self.allow.exists())
            self.assertEqual(5, len(self.gates_before))
            trace.append("generate")
            return generate_worlds(**kwargs)

        generator = mock.Mock(side_effect=real_generator)
        with mock.patch.object(worlds, "verify_quiet", side_effect=verified), \
             mock.patch.object(safety.RootFS, "write_new", tracked_write), \
             mock.patch.object(safety.RootFS, "mkdir", tracked_mkdir), \
             mock.patch.object(safety.RootFS, "restore_record", tracked_restore):
            result = self.execute(generator=generator)
        self.assertEqual(("WORLD_GENERATED", "OK", "COMPLETE"),
                         (result["result"], result["reason"], result["stage"]), result)
        self.assertEqual(2, generator.call_count)
        self.assertEqual(["quiet-and-all-five-gates", "generate", "generate",
                          "quiet-and-all-five-gates", "quiet-and-all-five-gates"], trace)
        self.assertEqual(list(safety.GATE_UNITS), result["gates_verified"])
        self.assertTrue(result["scope_created"])
        self.assertEqual(self.scope, result["output_scope"])
        self.assertIs(result["restore_created"], True)
        self.assertEqual(self.restore_scope, result["restore_scope"])
        self.assertTrue(self.restore_path.is_dir())
        self.assertEqual([self.restore_scope, self.scope], directories)
        self.assertTrue(restores)
        self.assertTrue(all(path.startswith(self.restore_scope + "/") for path in restores), restores)
        self.assertEqual([self.scope + "/" + name for name in ("input.json", "worlds.json", "manifest.json")],
                         [path for path in writes if path.startswith(self.scope + "/")])
        self.assertTrue(all(path.startswith(self.restore_scope + "/") or path.startswith(self.scope + "/")
                            for path in writes), writes)
        self.assertEqual(0o700, self.scope_path.stat().st_mode & 0o777)
        self.assertEqual({"input.json", "worlds.json", "manifest.json"},
                         {path.name for path in self.scope_path.iterdir()})
        self.assertEqual(validator.INPUT_BYTES, (self.scope_path / "input.json").read_bytes())
        self.assertEqual(self.good_bytes, (self.scope_path / "worlds.json").read_bytes())
        self.assertTrue(result["validation"]["valid"])
        self.assertEqual((256, 256, 8836),
                         (result["validation"]["accepted"],
                          result["validation"]["distinct_worlds"],
                          result["validation"]["attempts"]))
        artifact = result["artifact"]
        self.assertEqual(self.good_bytes, zlib.decompress(base64.b64decode(artifact["data"], validate=True)))
        self.assertEqual(("worlds.json", len(self.good_bytes), self.good_sha256, "zlib+base64"),
                         (artifact["name"], artifact["bytes"], artifact["sha256"], artifact["encoding"]))
        manifest_raw = (self.scope_path / "manifest.json").read_bytes()
        manifest = json.loads(manifest_raw)
        self.assertEqual(worlds.canonical(manifest), manifest_raw)
        self.assertEqual(dict(
            schema="bridge.ibm.school-worlds.manifest.v1", run_id=self.p["run_id"],
            source_commit=self.p["head"], snapshot_id=worlds.SNAPSHOT_ID,
            snapshot_sha256=self.fixture_sha, generator_sha256=worlds.GENERATOR_SHA256,
            input_sha256=validator.INPUT_SHA256, worlds_sha256=self.good_sha256,
            worlds_bytes=len(self.good_bytes), python_version=result["python_version"],
            identical_repeats=2, purpose="COMPUTE_VERIFICATION_AND_TRAINING_INPUT_ONLY",
            service_changes=[]), manifest)
        self.assert_immutable_evidence()
        self.assertTrue(self.fx.calls)

