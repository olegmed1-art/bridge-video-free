class MainLifecycleTests(unittest.TestCase):
    def run_main(self, *, parent_ids=(42, 42), prctl_result=0, interrupt=None, active_timer=(0.0, 0.0)):
        stdout = mock.Mock()
        stdout.buffer = io.BytesIO()
        handlers = {}
        originals = {sig: object() for sig in (signal.SIGALRM, signal.SIGTERM, signal.SIGINT, signal.SIGHUP)}
        calls = []

        def install(sig, handler):
            calls.append((sig, handler))
            handlers[sig] = handler
            return originals[sig]

        library = mock.Mock()
        library.prctl.return_value = prctl_result
        blocked = dict(schema=worlds.RECEIPT_SCHEMA, result="BLOCKED", reason="REQUEST_INVALID", artifact=None)
        successful = dict(schema=worlds.RECEIPT_SCHEMA, result="WORLD_GENERATED", reason="OK", artifact=None)

        def execute(p, **_kwargs):
            if p is None:
                return copy.deepcopy(blocked)
            if interrupt is not None:
                handlers[interrupt](interrupt, None)
            return copy.deepcopy(successful)

        with mock.patch.object(worlds.platform, "system", return_value="Linux"), \
             mock.patch.object(worlds.os, "geteuid", return_value=0), \
             mock.patch.object(worlds.os, "getppid", side_effect=parent_ids), \
             mock.patch.object(worlds.ctypes, "CDLL", return_value=library), \
             mock.patch.object(worlds.signal, "getitimer", return_value=active_timer), \
             mock.patch.object(worlds.signal, "setitimer") as timer, \
             mock.patch.object(worlds.signal, "signal", side_effect=install), \
             mock.patch.object(worlds, "execute", side_effect=execute) as executing, \
             mock.patch.object(worlds.sys, "stdout", stdout):
            code = worlds.main({"offline": True})
        raw = stdout.buffer.getvalue()
        receipt = json.loads(raw)
        self.assertEqual(worlds.canonical(receipt), raw)
        if active_timer == (0.0, 0.0):
            self.assertEqual(8, len(calls))
            self.assertEqual([(sig, originals[sig]) for sig in originals], calls[4:])
            self.assertEqual(mock.call(signal.ITIMER_REAL, 0), timer.call_args_list[-1])
            self.assertGreater(timer.call_args_list[0].args[1], 0)
            self.assertLessEqual(timer.call_args_list[0].args[1], worlds.SECONDS)
        return code, receipt, library, executing, timer, calls

    def test_parent_death_signal_is_installed_and_handlers_and_alarm_are_restored(self):
        code, receipt, library, executing, _timer, _calls = self.run_main()
        self.assertEqual((0, "WORLD_GENERATED", "OK"), (code, receipt["result"], receipt["reason"]))
        library.prctl.assert_called_once_with(1, signal.SIGTERM)
        executing.assert_called_once_with({"offline": True}, started=worlds._STARTED)

    def test_missing_changed_parent_and_prctl_failure_block_before_work(self):
        for parents, prctl in (((1,), 0), ((42, 43), 0), ((42,), -1)):
            with self.subTest(parents=parents, prctl=prctl):
                code, receipt, _library, executing, _timer, _calls = self.run_main(
                    parent_ids=parents, prctl_result=prctl)
                self.assertEqual((3, "BLOCKED", "PARENT_LOST"), (code, receipt["result"], receipt["reason"]))
                executing.assert_called_once_with(None)

    def test_alarm_and_cancellation_abort_and_always_restore_handlers(self):
        for sig in (signal.SIGALRM, signal.SIGTERM, signal.SIGINT, signal.SIGHUP):
            with self.subTest(signal=sig):
                code, receipt, _library, executing, _timer, _calls = self.run_main(interrupt=sig)
                self.assertEqual((3, "BLOCKED", "DEADLINE" if sig == signal.SIGALRM else "CANCELLED"),
                                 (code, receipt["result"], receipt["reason"]))
                self.assertEqual([mock.call({"offline": True}, started=worlds._STARTED), mock.call(None)],
                                 executing.call_args_list)

    def test_preexisting_alarm_is_not_overwritten_or_cancelled(self):
        code, receipt, library, executing, timer, calls = self.run_main(active_timer=(3.0, 0.0))
        self.assertEqual((3, "BLOCKED", "INTERNAL_BLOCKED"), (code, receipt["result"], receipt["reason"]))
        self.assertEqual([], calls)
        timer.assert_not_called()
        library.prctl.assert_not_called()
        executing.assert_called_once_with(None)


