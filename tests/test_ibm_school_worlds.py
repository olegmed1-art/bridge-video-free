    def test_failed_restore_mkdir_and_file_keep_truthful_scope_evidence(self):
        for number, fault in enumerate(("mkdir_before", "mkdir_after", "restore_file")):
            with self.subTest(fault=fault):
                if number:
                    self.make_fixture()
                mkdir = safety.RootFS.mkdir
                write = safety.RootFS.write_new

                def fail_mkdir(fs, path, **kwargs):
                    if path == self.restore_scope and fault == "mkdir_before":
                        raise OSError("OFFLINE_RESTORE_MKDIR_FAILURE")
                    answer = mkdir(fs, path, **kwargs)
                    if path == self.restore_scope and fault == "mkdir_after":
                        raise OSError("OFFLINE_RESTORE_MKDIR_FSYNC_FAILURE")
                    return answer

                def fail_write(fs, path, data, **kwargs):
                    if path.startswith(self.restore_scope + "/") and fault == "restore_file":
                        raise OSError("OFFLINE_RESTORE_FILE_FAILURE")
                    return write(fs, path, data, **kwargs)

                generator = mock.Mock()
                with mock.patch.object(safety.RootFS, "mkdir", fail_mkdir), \
                     mock.patch.object(safety.RootFS, "write_new", fail_write):
                    result = self.execute(generator=generator)
                self.assert_blocked(result, "INTERNAL_BLOCKED", before_scope=True)
                self.assertEqual(self.restore_scope, result["restore_scope"])
                if fault == "restore_file":
                    self.assertIs(result["restore_created"], True)
                else:
                    self.assertIsNone(result["restore_created"])
                self.assertEqual(fault != "mkdir_before", self.restore_path.exists())
                self.assertEqual("REQUEST", result["stage"])
                generator.assert_not_called()
                self.assert_immutable_evidence()

